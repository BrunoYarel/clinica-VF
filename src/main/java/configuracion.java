    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        // 1. Obtener el texto ingresado en cada campo de texto (JTextField)
// Asegúrate de que los nombres coincidan con tus variables (jTextField1, jTextField2, etc.)
String nombreClinica = txtNombre.getText().trim();
String telefono      = txtTelefono.getText().trim();
String direccion     = txtDireccion.getText().trim();
String correo        = txtCorreo.getText().trim();
String ciudad        = txtCiudad.getText().trim();
String region        = txtRegion.getText().trim();


// 2. Validar que el usuario no deje campos en blanco
if (nombreClinica.isEmpty() || telefono.isEmpty() || direccion.isEmpty() || 
    correo.isEmpty() || ciudad.isEmpty() || region.isEmpty()) {
    
    // Muestra una alerta de error si falta algún dato
    javax.swing.JOptionPane.showMessageDialog(this, 
            "Por favor, complete todos los campos de la configuración.", 
            "Campos Incompletos", 
            javax.swing.JOptionPane.WARNING_MESSAGE);
} else {
    // 3. AQUÍ SE GUARDAN LOS DATOS
    // (Aquí puedes agregar tu conexión a Base de Datos o persistencia de datos)
    
    // 4. Confirmación de éxito al usuario
    javax.swing.JOptionPane.showMessageDialog(this, 
            "Los cambios de la clínica se han guardado con éxito.", 
            "Configuración Guardada", 
            javax.swing.JOptionPane.INFORMATION_MESSAGE);
            
    // Cierra la ventana una vez guardado
    this.dispose(); 
}

    }//GEN-LAST:event_btnGuardarActionPerformed

